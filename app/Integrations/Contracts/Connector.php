<?php

namespace App\Integrations\Contracts;

use App\Enums\ConnectionMethod;
use App\Enums\EcommercePlatform;
use App\Integrations\Data\NormalizedOrder;
use App\Integrations\Data\VerifiedEvent;
use App\Integrations\Exceptions\InvalidWebhook;
use App\Integrations\Exceptions\UnsupportedCapability;
use App\Models\WebshopConnection;
use Carbon\CarbonImmutable;
use Illuminate\Http\Request;

/**
 * One implementation per ecommerce platform (Trello #1 "Connector
 * interface"). Connectors are stateless; connection-specific data lives
 * on WebshopConnection.
 */
interface Connector
{
    public function platform(): EcommercePlatform;

    public function method(): ConnectionMethod;

    /**
     * Platform-specific setup steps, including where to paste the webhook URL.
     *
     * @return array<string, mixed>
     */
    public function setupInstructions(WebshopConnection $connection, string $webhookUrl): array;

    /**
     * Validates merchant input and returns the credentials to store
     * (encrypted). Generated secrets are included so they can be shown once.
     *
     * @param  array<string, mixed>  $input
     * @return array<string, string>
     */
    public function connect(WebshopConnection $connection, array $input): array;

    /**
     * Validation rules for connect() input.
     *
     * @return array<string, mixed>
     */
    public function connectRules(): array;

    /**
     * Credential keys generated by Shopbonus and shown to the merchant once.
     *
     * @return list<string>
     */
    public function generatedSecrets(): array;

    /**
     * Active API check where the platform allows one.
     *
     * @return array{ok: bool, code: string}
     *
     * @throws UnsupportedCapability
     */
    public function testConnection(WebshopConnection $connection): array;

    /**
     * Proves the request came from the provider for this connection.
     *
     * @throws InvalidWebhook
     */
    public function verifyIncomingEvent(WebshopConnection $connection, Request $request): VerifiedEvent;

    /**
     * @return array<string, mixed>
     *
     * @throws UnsupportedCapability
     */
    public function fetchOrder(WebshopConnection $connection, string $externalId): array;

    /**
     * @param  array<string, mixed>  $payload  decoded event body
     */
    public function normalizeOrder(array $payload): NormalizedOrder;

    /**
     * For refund-only events: the external order ID the refund belongs to (null if not a refund).
     *
     * @param  array<string, mixed>  $payload
     */
    public function refundTarget(array $payload): ?string;

    /**
     * @return iterable<array<string, mixed>>
     *
     * @throws UnsupportedCapability
     */
    public function syncOrders(WebshopConnection $connection, CarbonImmutable $since): iterable;

    public function disconnect(WebshopConnection $connection): void;
}
